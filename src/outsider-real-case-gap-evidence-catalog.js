export function verifyRealCaseGapEvidenceCatalog(value) {
  try {
    if (!exactKeys(value, ["schema", "schemaVersion", "asOf", "searchScope",
      "evidencePrinciple", "temporalAuthenticityBoundary", "sources", "gaps",
      "counts", "verificationBoundary", "catalogHash"])) {
      fail("REAL_CASE_GAP_CATALOG_SCHEMA_INVALID");
    }
    const expected = buildRealCaseGapEvidenceCatalog({ asOf: value.asOf });
    if (canonicalizeStrict(expected) !== canonicalizeStrict(value)) {
      fail("REAL_CASE_GAP_CATALOG_MISMATCH");
    }
    return deepFreeze({
      ok: true,
      verificationLevel:
        "CODE_FIXED_CATALOG_WITH_PINNED_TEMPORAL_AUDIT_REFERENCE_STRUCTURE_ONLY",
      catalogHash: value.catalogHash,
      gapCoverageStructureVerified: true,
      sourceArtifactsReverified: false,
      temporalAuditReverified: false,
      temporalQuarantineReceiptCount: 7,
      currentCoverageReceiptCountClaimedByCatalogAlone: 0,
      webCompletenessEstablished: false,
      outsiderSpecificGapsClosed: 0,
      institutionalAuthorityGranted: false,
    });
  } catch (error) {
    return deepFreeze({
      ok: false,
      verificationLevel: "INVALID",
      error: error instanceof Error ? error.message : String(error),
      gapCoverageStructureVerified: false,
      sourceArtifactsReverified: false,
      temporalAuditReverified: false,
      temporalQuarantineReceiptCount: null,
      currentCoverageReceiptCountClaimedByCatalogAlone: 0,
      webCompletenessEstablished: false,
      outsiderSpecificGapsClosed: 0,
      institutionalAuthorityGranted: false,
    });
  }
}

  for (const item of SOURCES) validateSource(item);
  const sourceIds = new Set(SOURCES.map((item) => item.sourceId));
  if (sourceIds.size !== SOURCES.length) fail("REAL_CASE_GAP_SOURCE_DUPLICATE");
